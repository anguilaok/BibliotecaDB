-- TP1 Biblioteca - 20 consultas solicitadas
USE biblioteca;

-- 1. Libros ordenados del más antiguo al más nuevo.
SELECT TITULO, AGNO FROM LIBROS ORDER BY AGNO ASC;

-- 2. Estudiantes mayores de 25 años.
SELECT NOMBRES, APELLIDOS, EDAD FROM ESTUDIANTES WHERE EDAD > 25;

-- 3. Libros de la editorial ID_EDIT = 3.
SELECT TITULO, AGNO FROM LIBROS WHERE ID_EDIT = 3;

-- 4. Autores cuyo apellido comienza con M.
SELECT * FROM AUTORES WHERE APELLIDOS LIKE 'M%';

-- 5. Funcionarios con salud distinta de Buena.
SELECT NOMBRES, APELLIDOS FROM FUNCIONARIOS WHERE SALUD <> 'Buena';

-- 6. Título del libro y nombre completo del autor.
SELECT L.TITULO, CONCAT(A.NOMBRES, ' ', A.APELLIDOS) AS AUTOR
FROM LIBROS L JOIN AUTORES A ON L.RUT_AUTOR = A.RUT_AUTOR;

-- 7. Fecha, estudiante, libro y funcionario que atendió.
SELECT P.FECHA_P,
       CONCAT(E.NOMBRES, ' ', E.APELLIDOS) AS ESTUDIANTE,
       L.TITULO,
       CONCAT(F.NOMBRES, ' ', F.APELLIDOS) AS FUNCIONARIO
FROM PRESTAMO P
JOIN ESTUDIANTES E ON P.RUT_EST = E.RUT_EST
JOIN LIBROS L ON P.COD_LIBRO = L.COD_LIBRO
JOIN FUNCIONARIOS F ON P.RUT_FUNC = F.RUT_FUNC;

-- 8. Estudiante, carrera y ciudad donde estudia.
SELECT CONCAT(E.NOMBRES, ' ', E.APELLIDOS) AS ESTUDIANTE,
       C.NOMBRE AS CARRERA, CI.NOMBRE AS CIUDAD
FROM ESTUDIANTES E
JOIN CARRERAS C ON E.ID_CARRERA = C.ID_CARRERA
JOIN CAMPUS CA ON C.ID_CAMPUS = CA.ID_CAMPUS
JOIN CIUDAD CI ON CA.ID_CIUDAD = CI.ID_CIUDAD;

-- 9. Libros, editorial y país de origen.
SELECT L.TITULO, ED.NOMBRE AS EDITORIAL, ED.PAIS
FROM LIBROS L JOIN EDITORIALES ED ON L.ID_EDIT = ED.ID_EDIT;

-- 10. Libro y biblioteca donde se encuentra.
SELECT L.TITULO, B.BIBLIOTECA
FROM LIBROS L JOIN BIBLIOTECA B ON L.ID_BIBLIO = B.ID_BIBLIO;

-- 11. Cantidad de libros por tipo.
SELECT T.TIPO_P, COUNT(L.COD_LIBRO) AS CANTIDAD_LIBROS
FROM TIPO T LEFT JOIN LIBROS L ON T.ID_TIPO = L.ID_TIPO
GROUP BY T.ID_TIPO, T.TIPO_P;

-- 12. Edad promedio por carrera.
SELECT C.NOMBRE AS CARRERA, ROUND(AVG(E.EDAD), 2) AS EDAD_PROMEDIO
FROM CARRERAS C LEFT JOIN ESTUDIANTES E ON C.ID_CARRERA = E.ID_CARRERA
GROUP BY C.ID_CARRERA, C.NOMBRE;

-- 13. Funcionarios y cantidad de préstamos realizados.
SELECT CONCAT(F.NOMBRES, ' ', F.APELLIDOS) AS FUNCIONARIO,
       COUNT(P.COD_LIBRO) AS TOTAL_PRESTAMOS
FROM FUNCIONARIOS F LEFT JOIN PRESTAMO P ON F.RUT_FUNC = P.RUT_FUNC
GROUP BY F.RUT_FUNC, F.NOMBRES, F.APELLIDOS
ORDER BY TOTAL_PRESTAMOS DESC;

-- 14. Autores con más de un libro registrado.
SELECT A.RUT_AUTOR, A.NOMBRES, A.APELLIDOS, COUNT(L.COD_LIBRO) AS TOTAL_LIBROS
FROM AUTORES A JOIN LIBROS L ON A.RUT_AUTOR = L.RUT_AUTOR
GROUP BY A.RUT_AUTOR, A.NOMBRES, A.APELLIDOS
HAVING COUNT(L.COD_LIBRO) > 1;

-- 15. Ciudad y cantidad de estudiantes que estudian en campus de esa ciudad.
SELECT CI.NOMBRE AS CIUDAD, COUNT(DISTINCT E.RUT_EST) AS CANTIDAD_ESTUDIANTES
FROM CIUDAD CI
LEFT JOIN CAMPUS CA ON CI.ID_CIUDAD = CA.ID_CIUDAD
LEFT JOIN CARRERAS C ON CA.ID_CAMPUS = C.ID_CAMPUS
LEFT JOIN ESTUDIANTES E ON C.ID_CARRERA = E.ID_CARRERA
GROUP BY CI.ID_CIUDAD, CI.NOMBRE;

-- 16. Título y año del libro más antiguo.
SELECT TITULO, AGNO FROM LIBROS
WHERE AGNO = (SELECT MIN(AGNO) FROM LIBROS);

-- 17. Estudiantes que nunca han pedido un libro prestado.
SELECT E.RUT_EST, E.NOMBRES, E.APELLIDOS
FROM ESTUDIANTES E
WHERE NOT EXISTS (SELECT 1 FROM PRESTAMO P WHERE P.RUT_EST = E.RUT_EST);

-- 18. Libros que nunca fueron prestados.
SELECT L.COD_LIBRO, L.TITULO
FROM LIBROS L
WHERE NOT EXISTS (SELECT 1 FROM PRESTAMO P WHERE P.COD_LIBRO = L.COD_LIBRO);

-- 19. Préstamos realizados durante el mes calendario anterior.
SELECT * FROM PRESTAMO
WHERE FECHA_P >= DATE_FORMAT(CURDATE() - INTERVAL 1 MONTH, '%Y-%m-01')
  AND FECHA_P < DATE_FORMAT(CURDATE(), '%Y-%m-01');

-- 20. Los 3 libros más prestados.
SELECT L.COD_LIBRO, L.TITULO, COUNT(*) AS VECES_PRESTADO
FROM LIBROS L JOIN PRESTAMO P ON L.COD_LIBRO = P.COD_LIBRO
GROUP BY L.COD_LIBRO, L.TITULO
ORDER BY VECES_PRESTADO DESC
LIMIT 3;
