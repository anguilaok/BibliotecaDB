-- TP1 Biblioteca - Creación de la base de datos y sus tablas
CREATE DATABASE IF NOT EXISTS biblioteca
  CHARACTER SET utf8mb4
  COLLATE utf8mb4_unicode_ci;

USE biblioteca;

CREATE TABLE IF NOT EXISTS CIUDAD (
    ID_CIUDAD INT AUTO_INCREMENT PRIMARY KEY,
    NOMBRE VARCHAR(100) NOT NULL UNIQUE
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS CAMPUS (
    ID_CAMPUS INT AUTO_INCREMENT PRIMARY KEY,
    NOMBRE VARCHAR(100) NOT NULL,
    ID_CIUDAD INT NOT NULL,
    CONSTRAINT FK_CAMPUS_CIUDAD
      FOREIGN KEY (ID_CIUDAD) REFERENCES CIUDAD(ID_CIUDAD)
      ON UPDATE CASCADE ON DELETE RESTRICT
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS CARRERAS (
    ID_CARRERA INT AUTO_INCREMENT PRIMARY KEY,
    NOMBRE VARCHAR(120) NOT NULL,
    ID_CAMPUS INT NOT NULL,
    CONSTRAINT FK_CARRERAS_CAMPUS
      FOREIGN KEY (ID_CAMPUS) REFERENCES CAMPUS(ID_CAMPUS)
      ON UPDATE CASCADE ON DELETE RESTRICT
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS ESTUDIANTES (
    RUT_EST VARCHAR(15) PRIMARY KEY,
    NOMBRES VARCHAR(100) NOT NULL,
    APELLIDOS VARCHAR(100) NOT NULL,
    EDAD TINYINT UNSIGNED NOT NULL,
    FONO VARCHAR(25),
    DIRECCION VARCHAR(180),
    ID_CARRERA INT NOT NULL,
    CONSTRAINT CHK_ESTUDIANTES_EDAD CHECK (EDAD >= 0),
    CONSTRAINT FK_ESTUDIANTES_CARRERAS
      FOREIGN KEY (ID_CARRERA) REFERENCES CARRERAS(ID_CARRERA)
      ON UPDATE CASCADE ON DELETE RESTRICT
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS FUNCIONARIOS (
    RUT_FUNC VARCHAR(15) PRIMARY KEY,
    NOMBRES VARCHAR(100) NOT NULL,
    APELLIDOS VARCHAR(100) NOT NULL,
    EDAD TINYINT UNSIGNED NOT NULL,
    DIRECCION VARCHAR(180),
    SALUD VARCHAR(60) NOT NULL DEFAULT 'Buena',
    ID_CAMPUS INT NOT NULL,
    CONSTRAINT CHK_FUNCIONARIOS_EDAD CHECK (EDAD >= 0),
    CONSTRAINT FK_FUNCIONARIOS_CAMPUS
      FOREIGN KEY (ID_CAMPUS) REFERENCES CAMPUS(ID_CAMPUS)
      ON UPDATE CASCADE ON DELETE RESTRICT
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS BIBLIOTECA (
    ID_BIBLIO INT AUTO_INCREMENT PRIMARY KEY,
    BIBLIOTECA VARCHAR(120) NOT NULL
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS TIPO (
    ID_TIPO INT AUTO_INCREMENT PRIMARY KEY,
    TIPO_P VARCHAR(80) NOT NULL UNIQUE
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS AUTORES (
    RUT_AUTOR VARCHAR(15) PRIMARY KEY,
    NOMBRES VARCHAR(100) NOT NULL,
    APELLIDOS VARCHAR(100) NOT NULL
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS EDITORIALES (
    ID_EDIT INT AUTO_INCREMENT PRIMARY KEY,
    NOMBRE VARCHAR(120) NOT NULL,
    PAIS VARCHAR(80) NOT NULL
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS LIBROS (
    COD_LIBRO INT PRIMARY KEY,
    TITULO VARCHAR(200) NOT NULL,
    AGNO YEAR NOT NULL,
    ID_BIBLIO INT NOT NULL,
    ID_TIPO INT NOT NULL,
    RUT_AUTOR VARCHAR(15) NOT NULL,
    ID_EDIT INT NOT NULL,
    CONSTRAINT FK_LIBROS_BIBLIOTECA
      FOREIGN KEY (ID_BIBLIO) REFERENCES BIBLIOTECA(ID_BIBLIO)
      ON UPDATE CASCADE ON DELETE RESTRICT,
    CONSTRAINT FK_LIBROS_TIPO
      FOREIGN KEY (ID_TIPO) REFERENCES TIPO(ID_TIPO)
      ON UPDATE CASCADE ON DELETE RESTRICT,
    CONSTRAINT FK_LIBROS_AUTORES
      FOREIGN KEY (RUT_AUTOR) REFERENCES AUTORES(RUT_AUTOR)
      ON UPDATE CASCADE ON DELETE RESTRICT,
    CONSTRAINT FK_LIBROS_EDITORIALES
      FOREIGN KEY (ID_EDIT) REFERENCES EDITORIALES(ID_EDIT)
      ON UPDATE CASCADE ON DELETE RESTRICT
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS PRESTAMO (
    RUT_EST VARCHAR(15) NOT NULL,
    RUT_FUNC VARCHAR(15) NOT NULL,
    COD_LIBRO INT NOT NULL,
    FECHA_P DATE NOT NULL,
    FECHA_E DATE NULL,
    PRIMARY KEY (RUT_EST, RUT_FUNC, COD_LIBRO),
    CONSTRAINT FK_PRESTAMO_ESTUDIANTES
      FOREIGN KEY (RUT_EST) REFERENCES ESTUDIANTES(RUT_EST)
      ON UPDATE CASCADE ON DELETE RESTRICT,
    CONSTRAINT FK_PRESTAMO_FUNCIONARIOS
      FOREIGN KEY (RUT_FUNC) REFERENCES FUNCIONARIOS(RUT_FUNC)
      ON UPDATE CASCADE ON DELETE RESTRICT,
    CONSTRAINT FK_PRESTAMO_LIBROS
      FOREIGN KEY (COD_LIBRO) REFERENCES LIBROS(COD_LIBRO)
      ON UPDATE CASCADE ON DELETE RESTRICT,
    CONSTRAINT CHK_PRESTAMO_FECHAS CHECK (FECHA_E IS NULL OR FECHA_E >= FECHA_P)
) ENGINE=InnoDB;
