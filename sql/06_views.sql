-- TP1 Biblioteca - Vistas
USE biblioteca;

CREATE OR REPLACE VIEW VW_PRESTAMOS_DETALLE AS
SELECT P.FECHA_P AS FECHA_PRESTAMO,
       CONCAT(E.NOMBRES, ' ', E.APELLIDOS) AS ESTUDIANTE,
       L.TITULO AS LIBRO,
       CONCAT(F.NOMBRES, ' ', F.APELLIDOS) AS FUNCIONARIO,
       C.NOMBRE AS CARRERA,
       P.FECHA_E AS FECHA_ENTREGA
FROM PRESTAMO P
JOIN ESTUDIANTES E ON P.RUT_EST = E.RUT_EST
JOIN LIBROS L ON P.COD_LIBRO = L.COD_LIBRO
JOIN FUNCIONARIOS F ON P.RUT_FUNC = F.RUT_FUNC
JOIN CARRERAS C ON E.ID_CARRERA = C.ID_CARRERA;

-- El esquema entregado no relaciona BIBLIOTECA directamente con CIUDAD.
-- Por eso esta vista muestra biblioteca y cantidad de libros, sin inventar una ciudad.
CREATE OR REPLACE VIEW VW_LIBROS_POR_BIBLIOTECA AS
SELECT B.ID_BIBLIO,
       B.BIBLIOTECA,
       COUNT(L.COD_LIBRO) AS CANTIDAD_LIBROS
FROM BIBLIOTECA B
LEFT JOIN LIBROS L ON B.ID_BIBLIO = L.ID_BIBLIO
GROUP BY B.ID_BIBLIO, B.BIBLIOTECA;

-- Pruebas:
SELECT * FROM VW_PRESTAMOS_DETALLE;
SELECT * FROM VW_LIBROS_POR_BIBLIOTECA;
